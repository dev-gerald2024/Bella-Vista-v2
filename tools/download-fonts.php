<?php
/* Downloads Cormorant Garamond + Jost from Google Fonts ONCE (needs internet), saves the .woff2 files to
   assets/fonts/ and writes css/fonts.css so the site looks the same with no internet.
   Run from the project folder:   php tools/download-fonts.php
   (XAMPP: C:\xampp\php\php.exe tools\download-fonts.php)  Needs the PHP "openssl" extension enabled (it is in XAMPP). */
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }   // never runnable from the web
$root = dirname(__DIR__);
$cssUrl = 'https://fonts.googleapis.com/css2?family=Cormorant+Garamond:ital,wght@0,500;0,600;1,500&family=Jost:wght@300;400;500&display=swap';
$ctx = stream_context_create(['http' => ['header' => "User-Agent: Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36\r\n", 'timeout' => 30]]);

function build_local_css(string $css, callable $fetch): string {
  /* only keep the latin and latin-ext blocks (English + Filipino names); each block becomes one local @font-face */
  preg_match_all('#/\*\s*([a-z0-9-]+)\s*\*/\s*(@font-face\s*\{.*?\})#s', $css, $blocks, PREG_SET_ORDER);
  $out = "/* Generated by tools/download-fonts.php. Do not edit by hand. */\n";
  foreach ($blocks as [$all, $subset, $face]) {
    if (!in_array($subset, ['latin', 'latin-ext'], true)) continue;
    if (!preg_match('#url\((https://[^)]+\.woff2)\)#', $face, $u)) continue;
    $family = preg_match("#font-family:\s*'([^']+)'#", $face, $f) ? $f[1] : 'font';
    $style = preg_match('#font-style:\s*(\w+)#', $face, $s) ? $s[1] : 'normal';
    $weight = preg_match('#font-weight:\s*(\d+)#', $face, $w) ? $w[1] : '400';
    $name = strtolower(str_replace(' ', '-', $family)) . "-$style-$weight-$subset.woff2";
    $fetch($u[1], $name);
    $face = str_replace($u[1], "../assets/fonts/$name", $face);
    $out .= "/* $subset */\n$face\n";
  }
  return $out;
}

if (realpath($_SERVER['SCRIPT_FILENAME'] ?? '') !== __FILE__) return;   // included by tests/fonts_tool_check.php: only the functions are wanted

$css = @file_get_contents($cssUrl, false, $ctx);
if ($css === false) { fwrite(STDERR, "Could not reach Google Fonts. Check your internet connection and try again.\n"); exit(1); }
@mkdir("$root/assets/fonts", 0775, true);
$n = 0;
$local = build_local_css($css, function (string $url, string $name) use ($root, $ctx, &$n) {
  $bin = @file_get_contents($url, false, $ctx);
  if ($bin === false || strlen($bin) < 1000) { fwrite(STDERR, "Failed to download $name\n"); exit(1); }
  file_put_contents("$root/assets/fonts/$name", $bin); $n++;
});
if ($n === 0) { fwrite(STDERR, "No font files were found in Google's response. Nothing was changed.\n"); exit(1); }
file_put_contents("$root/css/fonts.css", $local);
echo "Done: $n font files saved to assets/fonts/ and css/fonts.css written.\n";
